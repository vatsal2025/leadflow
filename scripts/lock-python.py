"""Lock the installed dependency graph for both runtime and development.

Run after updating requirements*.in in an isolated, installed virtualenv.
"""

from importlib.metadata import distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parents[1] / "backend"


def resolve(roots):
    pins = {}
    pending = list(roots)
    while pending:
        requirement = Requirement(pending.pop())
        if requirement.marker and not requirement.marker.evaluate():
            continue
        name = canonicalize_name(requirement.name)
        if name in pins:
            continue
        dist = distribution(name)
        pins[name] = dist.version
        for dependency in dist.requires or []:
            parsed = Requirement(dependency)
            if parsed.marker is None or any(parsed.marker.evaluate({"extra": extra}) for extra in ["", *requirement.extras]):
                pending.append(str(parsed).split(";")[0])
    return [f"{name}=={version}" for name, version in sorted(pins.items())]


runtime = (root / "requirements.in").read_text().splitlines()
dev = [line for line in (root / "requirements-dev.in").read_text().splitlines() if not line.startswith("-r")]
header = "# Generated by scripts/lock-python.py. Update .in files, install, then regenerate.\n"
for filename, dependencies in [("requirements.txt", runtime), ("requirements-dev.txt", [*runtime, *dev])]:
    (root / filename).write_text(header + "\n".join(resolve(dependencies)) + "\n", encoding="utf-8")
